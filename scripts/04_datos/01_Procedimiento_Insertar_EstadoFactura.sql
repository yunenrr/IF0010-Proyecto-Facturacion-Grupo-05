    EXEC DBO.PR_INSERTARESTADOFACTURA
        @ESTADO_FACTURA = 'PAGADA',
        @DESCRIPCION = 'Factura cancelada',
        @CODIGO_ERROR = @ERR OUTPUT,
        @MENSAJE_ERROR = @MSG OUTPUT;
END;

IF NOT EXISTS (
    SELECT 1
    FROM DBO.ESTADO_FACTURA
