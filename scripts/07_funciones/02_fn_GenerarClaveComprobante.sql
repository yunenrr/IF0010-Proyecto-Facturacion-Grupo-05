USE FACTURACION_SA;
GO

-- INICIO
IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_GENERAR_CLAVE_COMPROBANTE'
            AND TYPE = 'FN'
    )
BEGIN
    DROP FUNCTION DBO.FN_GENERAR_CLAVE_COMPROBANTE;
END;
GO

CREATE FUNCTION DBO.FN_GENERAR_CLAVE_COMPROBANTE(
    @FECHA DATETIME2,
    @TIPO_DOCUMENTO VARCHAR(30)
)
RETURNS VARCHAR(50)
AS
BEGIN
    DECLARE @FECHA_TXT VARCHAR(14);
    DECLARE @CLAVE VARCHAR(50);

    IF @FECHA IS NULL OR @TIPO_DOCUMENTO IS NULL
    BEGIN
        RETURN NULL;
    END;

    SET @FECHA_TXT
        = CONVERT(VARCHAR(8), @FECHA, 112)
        + REPLACE(CONVERT(VARCHAR(8), @FECHA, 108), ':', '');

    SET @CLAVE = CONCAT(@FECHA_TXT, '-', @TIPO_DOCUMENTO);

    RETURN @CLAVE;
END;
GO
-- FIN
