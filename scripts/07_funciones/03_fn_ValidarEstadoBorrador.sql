USE FACTURACION_SA;
GO

-- INICIO
IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_VALIDAR_ESTADO_BORRADOR'
            AND TYPE = 'FN'
    )
BEGIN
    DROP FUNCTION DBO.FN_VALIDAR_ESTADO_BORRADOR;
END;
GO

CREATE FUNCTION DBO.FN_VALIDAR_ESTADO_BORRADOR(
    @IDENTIFICADOR_FACTURA VARCHAR(50)
)
RETURNS BIT
AS
BEGIN
    DECLARE @RESULTADO BIT;

    IF @IDENTIFICADOR_FACTURA IS NULL
    BEGIN
        RETURN 0;
    END;

    IF
        EXISTS (
            SELECT 1
            FROM DBO.FACTURA AS F
            INNER JOIN DBO.ESTADO_FACTURA AS EF
                ON F.ID_ESTADO_FACTURA = EF.ID
            WHERE
                F.IDENTIFICADOR_FACTURA = @IDENTIFICADOR_FACTURA
                AND UPPER(EF.ESTADO_FACTURA) = 'BORRADOR'
        )
    BEGIN
        SET @RESULTADO = 1;
    END;

    RETURN @RESULTADO;
END;
GO
-- FIN
