--Crear función de tabla de seguridad
IF OBJECT_ID('DBO.FN_CONSULTAR_HISTORIAL', 'IF') IS NOT NULL
BEGIN
    DROP FUNCTION DBO.FN_CONSULTAR_HISTORIAL;
END;
GO

CREATE FUNCTION DBO.FN_CONSULTAR_HISTORIAL()
RETURNS TABLE
AS
RETURN (
    SELECT
        ID,
        ID_FACTURA,
        ID_REGISTRO_AFECTADO,
        OPERACION_REALIZADA,
        ESTADO_PREVIO,
        ESTADO_NUEVO,
        FECHA_HORA,
        TABLA_AFECTADA,
        DESCRIPCION,
        USUARIO_RESPONSABLE
    FROM DBO.HISTORIAL
    WHERE
        IS_ROLEMEMBER('Auditor') = 1
        OR IS_ROLEMEMBER('DBA') = 1
        OR IS_SRVROLEMEMBER('sysadmin') = 1
);
GO
