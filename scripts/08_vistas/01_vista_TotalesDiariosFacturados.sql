USE FACTURACION_SA;
GO

-- INICIO
IF OBJECT_ID('DBO.VW_TOTALES_DIARIOS_FACTURADOS', 'V') IS NOT NULL
BEGIN
    DROP VIEW DBO.VW_TOTALES_DIARIOS_FACTURADOS;
END;
GO

CREATE VIEW DBO.VW_TOTALES_DIARIOS_FACTURADOS
AS
SELECT
    CAST(F.FECHA_EMISION AS DATE) AS FechaEmision,
    E.RAZON_SOCIAL AS NombreEmpresa,
    D.DESCRIPCION AS TipoDocumento,
    COUNT(F.ID) AS CantidadFacturas,
    SUM(ISNULL(F.SUBTOTAL, 0.00)) AS SubtotalAcumulado,
    SUM(ISNULL(F.TOTAL_DESCUENTO, 0.00)) AS TotalDescuentos,
    SUM(ISNULL(F.TOTAL_IMPUESTO, 0.00)) AS TotalImpuestos,
    SUM(ISNULL(F.MONTO_TOTAL, 0.00)) AS MontoTotalFacturado
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA AS E
    ON F.ID_EMPRESA = E.ID
INNER JOIN DBO.DOCUMENTO AS D
    ON F.CODIGO_IDENTIFICADOR_DOCUMENTO = D.CODIGO_IDENTIFICADOR
GROUP BY
    CAST(F.FECHA_EMISION AS DATE),
    E.RAZON_SOCIAL,
    D.DESCRIPCION;
GO
-- FIN
