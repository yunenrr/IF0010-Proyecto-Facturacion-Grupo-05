-- INICIO
CREATE TABLE DBO.HISTORIAL (
    ID INTEGER IDENTITY (1, 1) NOT NULL,
    ID_FACTURA INTEGER NOT NULL,
    ID_REGISTRO_AFECTADO INTEGER NOT NULL,
    OPERACION_REALIZADA VARCHAR(30) NOT NULL,
    ESTADO_PREVIO VARCHAR(25) NOT NULL DEFAULT '',
    ESTADO_NUEVO VARCHAR(25) NOT NULL DEFAULT '',
    FECHA_HORA DATETIME2 NOT NULL,
    TABLA_AFECTADA VARCHAR(50) NOT NULL,
    DESCRIPCION VARCHAR(200) NOT NULL DEFAULT 'N/A',
    USUARIO_RESPONSABLE VARCHAR(100) NOT NULL,
    CONSTRAINT PK_ID_HISTORIAL PRIMARY KEY (ID),
    CONSTRAINT FK_HISTORIAL_FACTURA FOREIGN KEY (ID_FACTURA)
    REFERENCES DBO.FACTURA (ID)
);
GO
