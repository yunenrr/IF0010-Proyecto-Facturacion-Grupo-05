USE FACTURACION_SA;

GO -- INICIO

CREATE TABLE PRODUCTO (
    ID INTEGER IDENTITY (1, 1) NOT NULL,
    CODIGO VARCHAR(30) UNIQUE NOT NULL,
    DESCRIPCION VARCHAR(70) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 2) NOT NULL,
    PORCENTAJE_IMPUESTO DECIMAL(5, 2) NOT NULL,
    ESTADO_ACTIVO BIT NOT NULL,
    FECHA_CREACION DATE NOT NULL,
    FECHA_VENCIMIENTO DATE,
    EXISTENCIAS INTEGER NOT NULL,
    TIPO_PRODUCTO VARCHAR(10) NOT NULL,
    CONSTRAINT PK_ID_PRODUCTO PRIMARY KEY (ID),
    CONSTRAINT CK_EXISTENCIAS_POSITIVAS CHECK (EXISTENCIAS >= 0),
    CONSTRAINT CK_TIPO_PRODUCTO CHECK (TIPO_PRODUCTO IN ('FISICO', 'DIGITAL'))
);

GO -- FIN
