CREATE TABLE DBO.DETALLE_FACTURA_SERVICIO (
    ID_FACTURA INT NOT NULL,
    NUMERO_LINEA INT NOT NULL,
    ID_SERVICIO INT NOT NULL,
    CANTIDAD INT NOT NULL,
    PRECIO_UNITARIO_VENTA DECIMAL(18, 2) NOT NULL,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL,
    MONTO_SUBTOTAL DECIMAL(18, 2) NOT NULL,
    MONTO_IMPUESTO DECIMAL(18, 2) NOT NULL,
    DESCRIPCION VARCHAR(100) NOT NULL,
    CONSTRAINT PK_DETALLE_FACTURA_SERVICIO
    PRIMARY KEY (ID_FACTURA, NUMERO_LINEA),
    CONSTRAINT FK_DET_SERV_FACTURA FOREIGN KEY (ID_FACTURA)
    REFERENCES DBO.FACTURA (ID),
    CONSTRAINT FK_DET_SERV_SERVICIO FOREIGN KEY (ID_SERVICIO)
    REFERENCES DBO.SERVICIO (ID)
);

GO --Fin
