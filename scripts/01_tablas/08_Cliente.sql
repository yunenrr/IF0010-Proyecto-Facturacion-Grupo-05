CREATE TABLE DBO.CLIENTE (
    ID INTEGER IDENTITY (1, 1) NOT NULL,
    CEDULA VARCHAR(30) UNIQUE NOT NULL,
    TELEFONO VARCHAR(20) UNIQUE NOT NULL,
    NOMBRE VARCHAR(70) NOT NULL,
    PRIMER_APELLIDO VARCHAR(70) NOT NULL,
    SEGUNDO_APELLIDO VARCHAR(70) NOT NULL,
    CORREO_ELECTRONICO VARCHAR(100) UNIQUE NOT NULL,
    FECHA_ULTIMA_ACTUALIZACION DATE NOT NULL,
    FECHA_CREACION DATE NOT NULL,
    ID_DIRECCION INTEGER NOT NULL,
    CONSTRAINT PK_ID_CLIENTE PRIMARY KEY (ID),
    CONSTRAINT FK_DIRECCION_CLIENTE FOREIGN KEY (ID_DIRECCION)
    REFERENCES DBO.DIRECCION (ID_DIRECCION)
);
GO
