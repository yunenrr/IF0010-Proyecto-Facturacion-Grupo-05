USE Facturacion_SA;

GO -- INICIO

CREATE TABLE PROVINCIA(
ID_PROVINCIA INTEGER IDENTITY(1,1),
NOMBRE VARCHAR (30) UNIQUE NOT NULL,
DETALLE_PROVINCIA VARCHAR (100) NOT NULL,
CONSTRAINT PK_ID_PROVINCIA PRIMARY KEY (ID_PROVINCIA));


CREATE TABLE CANTON(
ID_CANTON INTEGER IDENTITY(1,1),
NOMBRE VARCHAR (30) UNIQUE NOT NULL,
DETALLE_CANTON VARCHAR (100) NOT NULL,
CONSTRAINT PK_ID_CANTON PRIMARY KEY (ID_CANTON));


CREATE TABLE DISTRITO(
ID_DISTRITO INTEGER IDENTITY(1,1),
NOMBRE VARCHAR (30) NOT NULL,
DETALLE_DISTRITO VARCHAR (100) NOT NULL,
CONSTRAINT PK_ID_DISTRITO PRIMARY KEY (ID_DISTRITO));


CREATE TABLE DIRECCION (
    ID_DIRECCION INTEGER IDENTITY (1, 1),
    ID_PROVINCIA INTEGER NOT NULL,
    ID_CANTON INTEGER NOT NULL,
    ID_DISTRITO INTEGER NOT NULL,
    DETALLE_DIRECCION VARCHAR(100) NOT NULL,
    CONSTRAINT PK_ID_DIRECCIÓN PRIMARY KEY (ID_DIRECCION),
    CONSTRAINT FK_ID_PROVINCIA FOREIGN KEY (ID_PROVINCIA)
    REFERENCES PROVINCIA(ID_PROVINCIA),
    CONSTRAINT FK_ID_CANTON FOREIGN KEY (ID_CANTON)
    REFERENCES CANTON(ID_CANTON));

GO -- FIN
