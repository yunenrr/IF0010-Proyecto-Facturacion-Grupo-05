USE FACTURACION_SA;

GO -- INICIO

CREATE TABLE DETALLE_FACTURA (
    ID_FACTURA INTEGER NOT NULL,
    NUMERO_LINEA INTEGER NOT NULL,
    ID_PRODUCTO INTEGER NOT NULL,
    CANTIDAD INTEGER NOT NULL,
    PRECIO_UNITARIO_VENTA DECIMAL(18, 2) NOT NULL,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL,
    MONTO_SUBTOTAL DECIMAL(18, 2) NOT NULL,
    MONTO_IMPUESTO DECIMAL(18, 2) NOT NULL,
    DESCRIPCION VARCHAR(100),
    CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY (ID_FACTURA, NUMERO_LINEA),
    CONSTRAINT FK_DETALLE_FACTURA_FACTURA
    FOREIGN KEY (ID_FACTURA)
    REFERENCES FACTURA (ID),
    CONSTRAINT FK_DETALLE_FACTURA_PRODUCTO
    FOREIGN KEY (ID_PRODUCTO)
    REFERENCES PRODUCTO (ID),
    CONSTRAINT CK_DETALLE_FACTURA_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETALLE_FACTURA_PRECIO CHECK (PRECIO_UNITARIO_VENTA > 0),
    CONSTRAINT CK_DETALLE_FACTURA_DESCUENTO CHECK (MONTO_DESCUENTO >= 0),
    CONSTRAINT CK_DETALLE_FACTURA_SUBTOTAL CHECK (MONTO_SUBTOTAL > 0),
    CONSTRAINT CK_DETALLE_FACTURA_IMPUESTO CHECK (MONTO_IMPUESTO >= 0)
);

GO -- FIN
