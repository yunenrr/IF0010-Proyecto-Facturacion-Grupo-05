USE FACTURACION_SA;

GO -- INICIO

CREATE TABLE DIRECCION (
    ID_DIRECCION INTEGER IDENTITY (1, 1),
    ID_PROVINCIA INTEGER NOT NULL,
    ID_CANTON INTEGER NOT NULL,
    ID_DISTRITO INTEGER NOT NULL,
    DETALLE_DIRECCION VARCHAR(100) NOT NULL,
    CONSTRAINT PK_ID_DIRECCION PRIMARY KEY (ID_DIRECCION),
    CONSTRAINT FK_ID_PROVINCIA FOREIGN KEY (ID_PROVINCIA)
    REFERENCES PROVINCIA(ID_PROVINCIA),
    CONSTRAINT FK_ID_CANTON FOREIGN KEY (ID_CANTON)
    REFERENCES CANTON(ID_CANTON),
    CONSTRAINT FK_ID_DISTRITO FOREIGN KEY (ID_DISTRITO) 
    REFERENCES DISTRITO(ID_DISTRITO)
);

GO -- FIN






