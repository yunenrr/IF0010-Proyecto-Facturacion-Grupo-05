USE FACTURACION_SA;

GO -- INICIO

CREATE TABLE FACTURA (
    ID INTEGER IDENTITY (1, 1) NOT NULL,
    NUMERO_CONSECUTIVO INTEGER NOT NULL,
    FECHA_CREACION DATE NOT NULL,
    FECHA_MODIFICACION DATE NOT NULL,
    FECHA_EMISION DATE NOT NULL,
    SUBTOTAL DECIMAL(18, 2) NOT NULL,
    TOTAL_DESCUENTO DECIMAL(10, 2) NOT NULL,
    TOTAL_IMPUESTO DECIMAL(18, 2) NOT NULL,
    MONTO_TOTAL DECIMAL(19, 2) NOT NULL,
    OBSERVACIONES_ADICIONALES VARCHAR(100),
    CODIGO_MONEDA CHAR(3) NOT NULL,
    ID_ESTADO_FACTURA INTEGER NOT NULL,
    ID_EMPRESA INTEGER NOT NULL,
    ID_CLIENTE INTEGER NOT NULL,
    CODIGO_IDENTIFICADOR_DOCUMENTO INTEGER NOT NULL,
    CONSTRAINT PK_ID_FACTURA PRIMARY KEY (ID),
    CONSTRAINT FK_CODIGO_MONEDA
    FOREIGN KEY (CODIGO_MONEDA)
    REFERENCES MONEDA (CODIGO),
    CONSTRAINT FK_ESTADO_FACTURA
    FOREIGN KEY (ID_ESTADO_FACTURA)
    REFERENCES ESTADO_FACTURA (ID),
    CONSTRAINT FK_ID_EMPRESA
    FOREIGN KEY (ID_EMPRESA)
    REFERENCES EMPRESA (ID),
    CONSTRAINT FK_ID_CLIENTE
    FOREIGN KEY (ID_CLIENTE)
    REFERENCES CLIENTE (ID),
    CONSTRAINT FK_CODIGO_DOCUMENTO
    FOREIGN KEY (CODIGO_IDENTIFICADOR_DOCUMENTO)
    REFERENCES DOCUMENTO (CODIGO_IDENTIFICADOR),
    CONSTRAINT CK_FACTURA_DESCUENTO CHECK (TOTAL_DESCUENTO >= 0 AND TOTAL_DESCUENTO <= 100),
    CONSTRAINT CK_FACTURA_IMPUESTO CHECK (TOTAL_IMPUESTO >= 0),
    CONSTRAINT CK_FACTURA_MONTO_TOTAL CHECK (MONTO_TOTAL >= 0)
);

GO -- FIN
