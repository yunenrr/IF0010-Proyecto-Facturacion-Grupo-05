USE FACTURACION_SA;

GO--INICIO

CREATE TABLE dbo.HISTORIAL_DATOS (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ID_TABLA INT NOT NULL,                 
    ID_OPERACION INT NOT NULL,             
    ID_REGISTRO INT NOT NULL,               
    FECHA_HORA DATETIME2(7) NOT NULL DEFAULT SYSDATETIME(),
    DESCRIPCION VARCHAR(250) NOT NULL,
    USUARIO_RESPONSABLE VARCHAR(100) NOT NULL DEFAULT SUSER_SNAME(),
    
    CONSTRAINT FK_HistorialDatos_Tabla FOREIGN KEY (ID_TABLA) REFERENCES dbo.TABLA_AUDITADA(ID),
    CONSTRAINT FK_HistorialDatos_Operacion FOREIGN KEY (ID_OPERACION) REFERENCES dbo.TIPO_OPERACION(ID)
);

GO--FIN
