USE FACTURACION_SA;
GO

-- INICIO
IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'FN_CALCULAR_MONTO_FINAL'
            AND TYPE = 'FN'
    )
    BEGIN
        DROP FUNCTION DBO.FN_CALCULAR_MONTO_FINAL;
    END;
GO

CREATE FUNCTION DBO.FN_CALCULAR_MONTO_FINAL(
    @ID_FACTURA INT
)
RETURNS DECIMAL(19, 2)
AS
BEGIN
    DECLARE @MONTO_FINAL DECIMAL(19, 2);

    SELECT
        @MONTO_FINAL = (
            ISNULL(SUBTOTAL, 0.00)
            - ISNULL(TOTAL_DESCUENTO, 0.00)
            + ISNULL(TOTAL_IMPUESTO, 0.00)
        )
    FROM DBO.FACTURA
    WHERE ID = @ID_FACTURA;

    RETURN ISNULL(@MONTO_FINAL, 0.00);
END;
GO
-- FIN
