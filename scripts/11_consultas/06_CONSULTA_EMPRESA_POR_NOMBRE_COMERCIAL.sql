USE FACTURACION_SA;
GO

-- INICIO
IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'CONSULTA_EMPRESA_POR_NOMBRE_COMERCIAL'
            AND TYPE = 'P'
    )
    BEGIN
        DROP PROCEDURE DBO.CONSULTA_EMPRESA_POR_NOMBRE_COMERCIAL;
    END;
GO

CREATE PROCEDURE DBO.CONSULTA_EMPRESA_POR_NOMBRE_COMERCIAL (
    @NOMBRE_COMERCIAL VARCHAR(50)
)
AS
BEGIN
    SET NOCOUNT ON;

    SET @NOMBRE_COMERCIAL = TRIM(@NOMBRE_COMERCIAL);

    BEGIN TRY
        SELECT
            ID,
            CEDULA_JURIDICA,
            RAZON_SOCIAL,
            NOMBRE AS NOMBRE_COMERCIAL,
            CORREO_ELECTRONICO,
            TELEFONO,
            FECHA_CREACION,
            PERMISO_OPERAR
        FROM DBO.EMPRESA
        WHERE
            NOMBRE LIKE @NOMBRE_COMERCIAL + '%';
    END TRY
    BEGIN CATCH
        DECLARE @ERRORMSG VARCHAR(250) = ERROR_MESSAGE();
        
        RAISERROR (
            'Error al consultar empresa por nombre comercial: %s',
            16,
            1,
            @ERRORMSG
        );
    END CATCH;
END;
GO
