USE FACTURACION_SA;
GO

DECLARE @CEDULA_PRUEBA VARCHAR(30);

SELECT TOP 1 @CEDULA_PRUEBA = C.CEDULA
FROM DBO.CLIENTE AS C
INNER JOIN DBO.FACTURA AS F
    ON C.ID = F.ID_CLIENTE;

IF @CEDULA_PRUEBA IS NOT NULL
    BEGIN
        EXEC DBO.CONSULTA_FACTURAS_CLIENTE_FISICO
            @CEDULA_CLIENTE = @CEDULA_PRUEBA;
    END;
GO
