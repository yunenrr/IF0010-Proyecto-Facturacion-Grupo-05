IF
    EXISTS (
        SELECT 1
        FROM SYS.OBJECTS
        WHERE
            NAME = 'PR_EMITIRFACTURA'
            AND TYPE = 'P'
    )
BEGIN
    DROP PROCEDURE DBO.PR_EMITIRFACTURA;
END;
GO

CREATE PROCEDURE DBO.PR_EMITIRFACTURA (
    @NUMERO_CONSECUTIVO INT,
    @FECHA_CREACION DATE,
    @FECHA_MODIFICACION DATE,
    @FECHA_EMISION DATE,
    @SUBTOTAL DECIMAL(18, 2),
    @TOTAL_DESCUENTO DECIMAL(10, 2),
    @TOTAL_IMPUESTOS DECIMAL(19, 2),
    @MONTO_TOTAL DECIMAL(19, 2),
    @OBSERVACIONES VARCHAR(100),
    @CODIGO_MONEDA CHAR(3),
    @ID_ESTADO_FACTURA INT,
    @ID_EMPRESA INT,
    @ID_CLIENTE INT,
    @CODIGO_DOCUMENTO INT,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE_ERROR VARCHAR(255) OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;

    SET @CODIGO_ERROR = 0;
    SET @MENSAJE_ERROR = 'Exitoso';

    DECLARE @IDFACTURA INT;
    DECLARE @LINEASTOTALES INT = ((@NUMERO_CONSECUTIVO % 3) + 3);

    BEGIN TRY

        INSERT INTO DBO.FACTURA (
            NUMERO_CONSECUTIVO,
            FECHA_CREACION,
            FECHA_MODIFICACION,
            FECHA_EMISION,
            SUBTOTAL,
            TOTAL_DESCUENTO,
            TOTAL_IMPUESTO,
            MONTO_TOTAL,
            OBSERVACIONES_ADICIONALES,
            CODIGO_MONEDA,
            ID_ESTADO_FACTURA,
            ID_EMPRESA,
            ID_CLIENTE,
            CODIGO_IDENTIFICADOR_DOCUMENTO
        )
        VALUES (
            @NUMERO_CONSECUTIVO,
            ISNULL(@FECHA_CREACION, CAST(GETDATE() AS DATE)),
            ISNULL(@FECHA_MODIFICACION, CAST(GETDATE() AS DATE)),
            ISNULL(@FECHA_EMISION, CAST(GETDATE() AS DATE)),
            0.00,
            @TOTAL_DESCUENTO,
            0.00,
            0.00,
            ISNULL(@OBSERVACIONES, 'N/A'),
            @CODIGO_MONEDA,
            @ID_ESTADO_FACTURA,
            @ID_EMPRESA,
            @ID_CLIENTE,
            @CODIGO_DOCUMENTO
        );

        SET @IDFACTURA = SCOPE_IDENTITY();

        WITH NUMEROLINEA AS (
            SELECT 1 AS LINEA
            UNION ALL
            SELECT 2 AS LINEA
            UNION ALL
            SELECT 3 AS LINEA
            UNION ALL
            SELECT 4 AS LINEA
            WHERE @LINEASTOTALES >= 4
            UNION ALL
            SELECT 5 AS LINEA
            WHERE @LINEASTOTALES >= 5
        )

        INSERT INTO DBO.DETALLE_FACTURA (
            ID_FACTURA,
            NUMERO_LINEA,
            ID_PRODUCTO,
            CANTIDAD,
            PRECIO_UNITARIO_VENTA,
            MONTO_DESCUENTO,
            MONTO_SUBTOTAL,
            MONTO_IMPUESTO,
            DESCRIPCION
        )
        SELECT
            @IDFACTURA AS ID_FACTURA,
            NL.LINEA AS NUMERO_LINEA,
            CL.IDPROD AS ID_PRODUCTO,
            CL.CANT AS CANTIDAD,
            ISNULL(P.PRECIO_UNITARIO, 1000.00) AS PRECIO_UNITARIO_VENTA,
            ROUND((@TOTAL_DESCUENTO / @LINEASTOTALES), 2) AS MONTO_DESCUENTO,
            (ISNULL(P.PRECIO_UNITARIO, 1000.00) * CL.CANT)
                AS MONTO_SUBTOTAL,
            (
                (ISNULL(P.PRECIO_UNITARIO, 1000.00) * CL.CANT)
                * (ISNULL(P.PORCENTAJE_IMPUESTO, 13.00) / 100.0)
            )
                AS MONTO_IMPUESTO,
            'Detalle generado automaticamente' AS DESCRIPCION
        FROM NUMEROLINEA AS NL
        CROSS APPLY (
            SELECT
                (
                    (((@NUMERO_CONSECUTIVO * 5 + NL.LINEA) - 1) % 1000)
                    + 1
                ) AS IDPROD,
                (((@NUMERO_CONSECUTIVO + NL.LINEA) % 5) + 1) AS CANT
        ) AS CL
        LEFT JOIN DBO.PRODUCTO AS P
            ON CL.IDPROD = P.ID;

        WITH TOTALESDETALLE AS (
            SELECT
                DF.ID_FACTURA,
                SUM(DF.MONTO_SUBTOTAL) AS SUBTOTALSUM,
                SUM(DF.MONTO_IMPUESTO) AS IMPUESTOSUM
            FROM DBO.DETALLE_FACTURA AS DF
            WHERE
                DF.ID_FACTURA = @IDFACTURA
            GROUP BY
                DF.ID_FACTURA
        )

        UPDATE F
        SET
            SUBTOTAL = TD.SUBTOTALSUM,
            TOTAL_IMPUESTO = TD.IMPUESTOSUM,
            MONTO_TOTAL = TD.SUBTOTALSUM - F.TOTAL_DESCUENTO + TD.IMPUESTOSUM
        FROM DBO.FACTURA AS F
        INNER JOIN TOTALESDETALLE AS TD
            ON F.ID = TD.ID_FACTURA;

    END TRY
    BEGIN CATCH
        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE_ERROR = ERROR_MESSAGE();
    END CATCH;
END;
GO
